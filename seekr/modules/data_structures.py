class Seekr_model:
    warning: str = DONT_MODIFY_WARNING
    directory: str = field(default=".",
                            validator=validators.instance_of(str))
    seekr_version: str = field(default=__version__,
                               validator=validators.instance_of(str))
    # If the model format ever changes, we could read
    #  old model files and adapt them to the new format based
    #  on the version number.
    model_version: str = field(default="1.0",
                                 validator=validators.instance_of(str))
    username: str = field(default=getpass.getuser(),
                          validator=validators.instance_of(str))
    hostname: str = field(default=socket.gethostname(),
                          validator=validators.instance_of(str))
    synopsis_filename: str = field(default="SYNOPSIS",
                                   validator=validators.instance_of(str))
    log_directory: str = field(default="logs",)
                               #validator=validators.instance_of(str))
    images_and_plots_directory: str = field(default="images_and_plots",
                                            validator=validators.instance_of(str))
    temperature: float = field(default=298.15,
                               validator=[validators.instance_of(float),
                                          validators.gt(0)])
    is_toy_system: bool = field(default=False,
                                validator=validators.instance_of(bool))
    md_engine: engines_data_struct.MD_engine | None = None
    bd_engine: engines_data_struct.BD_engine | None = None
    stages: list[Stage] = field(default=Factory(list),)
                                #validator=validators.deep_iterable(
                                #    member_validator=Stage,
                                #    iterable_validator=validators.instance_of(list),
                                #))
    collective_variables: list[cv_data_struct.Collective_variable] \
        = field(default=Factory(list),)
            #validator=validators.deep_iterable(
            #    member_validator=validators.instance_of(
            #        cv_data_struct.Collective_variable),
            #    iterable_validator=validators.instance_of(list),
            #))
    num_anchors: int = field(default=0,
                             validator=[validators.instance_of(int),
                                        validators.ge(0)])
    num_milestones: int = field(default=0,
                                validator=[validators.instance_of(int),
                                           validators.ge(0)])
    anchors: list[Anchor] = field(default=Factory(list),)
                            #validator=validators.deep_iterable(
                            #    member_validator=Anchor,
                            #    iterable_validator=validators.instance_of(list),
                            #))
    
    def using_bd(self) -> bool:
        """
        Return whether this model is using BD
        """
        if self.bd_engine is None:
            return False
        else:
            return True
    
    def using_toy(self) -> bool:
        """
        Return whether this model is using BD
        """
        if self.is_toy_system:
            return True
        else:
            return False
    
    def get_md_timestep(self) -> float:
        """
        Return the timestep used in this model
        """
        if self.md_engine is not None:
            if isinstance(self.md_engine, openmm_base.Openmm_md_engine):
                assert self.md_engine.integrator_settings is not None, \
                    "integrator settings not provided."
                timestep: float = self.md_engine.integrator_settings.timestep
            else:
                raise Exception(
                    f"Timestep not available for md_engine {self.md_engine}.")
        else:
            raise Exception("MD engine settings not provided.")
        return timestep
    
    def get_bulk_index(self) -> int | None:
        """
        Get the anchor index of the bulk state. If there is no bulk state,
        return None.
        """
        bulk_index: int | None = None
        for alpha, anchor in enumerate(self.anchors):
            if anchor.bd and not anchor.md:
                #TODO: it could perhaps be convenient to have multiple bulk anchors
                # for simulation purposes, but is convenient for analysis to have
                # just one. Perhaps, we need a compromise where the anchors are modified
                # or copied over somehow with modifications and that contain only
                # one bulk anchor.
                assert bulk_index is None, "Only one bulk state is allowed "\
                    "in model"
                bulk_index = alpha
        return bulk_index
    
    def get_log_directory(
            self, 
            directory: str | None = None
            ) -> str:
        """
        Return the log directory for this model.
        """
        if directory is None:
            return os.path.join(self.directory, self.log_directory)
        else:
            return os.path.join(directory, self.log_directory)
        
    def get_synopsis_filename(
            self, 
            directory: str | None = None
            ) -> str:
        """
        Return the synopsis filename for this model.
        """
        log_directory: str = self.get_log_directory(directory)
        return os.path.join(log_directory, self.synopsis_filename)

    def save(
            self, 
            filename: str
            ) -> None:
        """
        Write the model object to a file.
        """
        #model.serialize(filename, xml_header=dont_modify_warning)
        seekr_model_dict: dict = cattrs.unstructure(self)
        seekr_model_dict_noindent: dict = base.wrap_noindent_integers(seekr_model_dict)
        json_dump: str = json.dumps(seekr_model_dict_noindent, indent=4, 
                                    cls=base.NoIndentListEncoder)
        with open(filename, "w") as file:
            #json.dump(seekr_input_dict, file, indent=4, cls=MyEncoder)
            file.write(json_dump)

        return
    
    def save_next_model(
            self, 
            model_glob: str, 
            model_base: str, 
            save_old_model: bool=True
            ) -> None:
        """
        Generate a new model file - the next in a series. The old model file(s) 
        will be renamed (optionally) with a numerical index.
        
        Parameters
        ----------
        model : Model()
            The Seekr Model object.
        model_glob : str
            The glob string that will be used to find all old model files.
            Only the base name of the file should be used, not the full path.
        model_base : str
            The base name of the model file. This will be used to rename the
            old model files.
        save_old_model : bool, Default True
            Whether to save the old model file with a new name. This can be
            convenient to set to False if the model should be serialized
            yet we don't care about saving some intermediate model values.
        """
        if self.md_engine is not None:
            if self.md_engine.platform_settings is not None:
                cuda_device_index: str = self.md_engine.platform_settings\
                    .device_index
                self.md_engine.platform_settings.device_index = "0"
            
        model_path: str = os.path.join(self.directory, "model.json")
        if os.path.exists(model_path) and save_old_model:
            # This is expected, because this old model was loaded
            full_model_glob: str = os.path.join(self.directory, model_glob)
            num_globs: int = len(glob.glob(full_model_glob))
            new_pre_model_filename: str = model_base.format(num_globs)
            new_pre_model_path: str = os.path.join(self.directory, 
                                                   new_pre_model_filename)
            logging.info("Renaming model.json to {}".format(new_pre_model_filename))
            copyfile(model_path, new_pre_model_path)
            
        logging.info("Saving new model.json")
        old_rootdir: str = self.directory
        self.directory = "."
        self.save(model_path)
        self.directory = old_rootdir
        if self.md_engine is not None:
            if self.md_engine.platform_settings is not None:
                self.md_engine.platform_settings.device_index\
                    = cuda_device_index
        return
    
def load_model(
        filename: str
        ) -> Seekr_model:
    """
    Load a model object from a file.
    """
    with open(filename, "r") as file:
        json_string: str = json.load(file)
    
    # Use a cattrs Converter to define how to structure the dictionary input
    converter: cattrs.Converter = cattrs.Converter()
    # Register a structure hook for the Positions_type
    converter.register_structure_hook(engines_base.Positions_type, 
                                      structure_positions_type_union)
    converter.register_structure_hook(Stage, structure_stage_type_union)
    model: Seekr_model = converter.structure(json_string, Seekr_model)
    return model

@define
class Anchor_input:
    """
    A base class for Anchor_inputs.

    In SEEKR, an anchor is a point in CV space. How this point
    is used within SEEKR depends on the enhanced sampling
    method. For instance, an anchor is used with MMVT to define
    a Voronoi cell, whose boundaries become the milestones. In
    Elber milestoning, two anchors are used to define two 
    Voronoi cells, and the milestone in between the two cells
    is the starting milestone, while the other boundaries define
    the ending milestones.
    """
    name: str = field(default="",
                           validator=validators.instance_of(str))
    value: list[float] = field(default=Factory(list),
                                validator=validators.deep_iterable(
                                    member_validator=[validators.instance_of(float)],
                                    iterable_validator=validators.instance_of(list),
                                ))
    md_parameters_topology: engines_base.Parameters_topology | None = None
    positions: engines_base.Positions_type = None
    selections: list[base.Selection] | None = field(default=None,
                                        validator=validators.optional(
                                            validators.deep_iterable(
                                                member_validator=validators.instance_of(base.Selection),
                                                iterable_validator=validators.instance_of(list),
                                            )))
    end_anchor: bool = field(default=False,
                            validator=validators.instance_of(bool))
    bulk_anchor: bool = field(default=False,
                            validator=validators.instance_of(bool))
    connection_flags: list[int] = field(default=Factory(list),
                                        validator=validators.deep_iterable(
                                            member_validator=[validators.instance_of(int)],
                                            iterable_validator=validators.instance_of(list),
                                        ))
    
    def check(self) -> None:
        """
        Check the anchor input for errors.
        """
        if self.bulk_anchor:
            assert self.end_anchor, "Bulk anchor must be an end anchor."
        return
    
    def get_variable_value(
            self,
            index: int
            ) -> float:
        """
        Return the variable value for this anchor.
        """
        return self.value[index]
    
    def same_md_parameters(
            self,
            other: "Anchor_input"
            ) -> bool:
        """

        """
        if self.md_parameters_topology is None:
            if other.md_parameters_topology is None:
                return True
            else:
                return False
        else:
            if other.md_parameters_topology is None:
                return False
            else:
                if self.md_parameters_topology.same_parameters(other.md_parameters_topology):
                    return True
                else:
                    return False
                
    def copy_initial_files(
            self, 
            anchor: Anchor, 
            root_directory: str,
            toy_mode: bool
            ) -> None:
        """
        Copy the files for the initial 'stage' from this Anchor_input
        to the actual anchor.
        """
        anchor_initial_directory: str = os.path.join(
            root_directory, anchor.directory, anchor.initial_directory)
        if toy_mode:
            anchor.positions = self.positions
        else:
            if self.md_parameters_topology is not None:
                self.md_parameters_topology.copy_files(anchor_initial_directory)
            if (self.positions is not None) and (self.positions != ""):
                assert isinstance(self.positions, str), \
                    "anchor.positions must be a filename str if not in Toy mode."
                pdb_basename: str = os.path.basename(self.positions)
                anchor_pdb_full_path: str = os.path.join(anchor_initial_directory,
                                                    pdb_basename)
                copyfile(os.path.expanduser(self.positions), anchor_pdb_full_path)
                anchor.positions = pdb_basename

