class Stage_md:
    """
    A md stage of the SEEKR calculation, whether that is an initial
    equilibration, a sampling method to obtain starting structures,
    a settling stage, or a production stage for obtaining kinetics.
    """
    type: typing.Literal["md_stage"] = "md_stage"
    index: int = field(default=0,
                        validator=[validators.instance_of(int),
                                      validators.ge(0)])
    name: str = field(default="equilibration", 
                      validator=validators.instance_of(str))
    run_minimization: bool = field(default=False,
                                      validator=validators.instance_of(bool))
    md_state_output_interval: int = field(default=0,
                                          validator=[validators.instance_of(int),
                                                        validators.ge(0)])
    md_trajectory_output_interval: int = field(default=0,
                                                validator=[validators.instance_of(int),
                                                            validators.ge(0)])
    md_restart_checkpoint_interval: int = field(default=0,
                                                validator=[validators.instance_of(int),
                                                            validators.ge(0)])
    ensemble: Ensemble = field(default=Factory(NVT_ensemble))
    sampling_method: sampling_methods_base.MD_sampling_method = field(
        default=Factory(sampling_methods_base.Conventional_md_sampling_method))
    completion_criteria: Completion_criteria = field(
        default=Factory(Number_of_steps_completion_criteria))
    # Whether this stage comes from the systemwide settings, if not,
    #  then it comes from the anchors. If None, then it is assigned automatically
    input_from_systemwide_settings: bool | None = field(default=None,
                                                    validator=validators.optional(
                                                      validators.instance_of(bool)))
    # Whether this stage outputs to the systemwide settings, if not,
    #  then it outputs to the anchors.  If None, then it is assigned automatically
    output_to_systemwide_settings: bool | None = field(default=None,
                                                validator=validators.optional(
                                                    validators.instance_of(bool)))

    def add_stage_directory_to_anchors(
            self, 
            model: "Seekr_model"
            ) -> None:
        """
        Add the stage directory to all anchors in the model.
        """
        for anchor in model.anchors:
            directory_name: str = f"stage_{self.index}_{self.name}"
            anchor.stage_directories.append(directory_name)
        return
    
    def add_stage_directory_to_systemwide_settings(
            self, 
            model: "Seekr_model"
            ) -> None:
        """
        Add the stage directory to the systemwide settings.
        """
        assert model.md_engine is not None, "MD stage provided, but "\
            "MD engine settings not provided."
        assert model.md_engine.systemwide_settings is not None, "MD engine systemwide "\
            "settings not provided, yet MD stage is provided."
        directory_name: str = f"stage_{self.index}_{self.name}"
        model.md_engine.systemwide_settings.stage_directories.append(directory_name)
        return

