    def has_files(
            self, 
            model: "Seekr_model"
            ) -> bool:
        """
        Returns true if any of the stage directories contain
        outputs from any of the stages.
        """
        stage_output_globs: list[str] = self.sampling_method.get_output_globs()
        my_directory = self.get_directory_name()
        for anchor in model.anchors:
            for stage_parameter in anchor.stage_parameters:
                stage_directory = stage_parameter["directory"]
                if stage_directory == my_directory:
                    for stage_output_glob in stage_output_globs:
                        output_files_glob = os.path.join(
                            model.directory, anchor.directory, stage_directory, 
                            stage_output_glob)
                        if len(glob.glob(output_files_glob)) > 0:
                            return True
        for stage_parameter in model.md_engine.systemwide_settings.stage_parameters:
            stage_directory = stage_parameter["directory"]
            if stage_directory == my_directory:
                for stage_output_glob in stage_output_globs:
                    output_files_glob = os.path.join(
                        model.directory, stage_directory, stage_output_glob)
                    if len(glob.glob(output_files_glob)) > 0:
                        return True
        return False
    
    def remove_directory(
            self, 
            model: "Seekr_model"
            ) -> None:
        """
        Remove entire directory in all anchors and systemwide settings for this stage.
        """
        my_directory = self._get_directory_name()
        for anchor in model.anchors:
            full_directory = os.path.join(model.directory, anchor.directory, my_directory)
            if os.path.exists(full_directory):
                rmtree(full_directory)
        full_directory = os.path.join(
            model.directory, model.md_engine.systemwide_settings.directory, my_directory)
        if os.path.exists(full_directory):
            rmtree(full_directory)
        return
                    
    def choose_next_simulation(
            self, 
            model: "Seekr_model", 
            anchor_index: str, 
            force_overwrite: bool,
            device_index: str | None = None
            ) -> list:
        assert model.md_engine is not None, "MD stage provided, but "\
            "MD engine settings not provided."
        if device_index is not None:
            assert model.md_engine.platform_settings is not None
            model.md_engine.platform_settings.device_index = \
                device_index
        
        min_total_sim_len = self.completion_criteria.get_min_sim_len()
        max_total_sim_len = self.completion_criteria.get_max_sim_len()
        
        anchor_info_to_run_unsorted: list = []
        if self.input_from_systemwide_settings:
            systemwide = model.md_engine.systemwide_settings
            num_swarm_frames = systemwide.get_starting_structure_num_frames(
                model, self.input_stage_index)
            for swarm_frame in range(num_swarm_frames):
                if num_swarm_frames <= 1:
                    swarm_frame = None
                current_step = systemwide.get_current_step(
                    self.index, swarm_frame, model.directory)
                restart_checkpoint_filename = anchor\
                    .get_restart_checkpoint_filename(
                        self.index, swarm_frame, model.directory)
                if (not os.path.exists(restart_checkpoint_filename)) \
                        or force_overwrite: # or umbrella_restart_mode:
                        # TODO: extract from sampling method whether restarts will be done
                    restart = False
                    current_step = 0
                else:
                    restart = True
                if current_step > max_total_sim_len:
                    # this simulation has run long enough
                    continue
                steps_to_go_to_min = min_total_sim_len - current_step
                if steps_to_go_to_min > run_base.STEP_TOLERANCE:
                    logging.info(
                        "Systemwide has not run the minimum number of steps",
                        current_step, "of", min_total_sim_len, 
                        "in swarm index", swarm_frame)
                    total_simulation_length = min_total_sim_len
                    num_transitions = 0
                    alpha = None
                    anchor_info = [steps_to_go_to_min, num_transitions, 
                                alpha, restart, total_simulation_length,
                                swarm_frame]
                    anchor_info_to_run_unsorted.append(anchor_info)

        else:
            for alpha, anchor in enumerate(model.anchors):
                if not anchor.md:
                    continue
                if anchor_index not in ["any"]:
                    try:
                        anchor_index_int = int(anchor_index)
                    except ValueError:
                        return []
                    if alpha != anchor_index_int:
                        continue
                
                num_swarm_frames = anchor.get_starting_structure_num_frames(
                    model, self.input_stage_index)
                
                for swarm_frame in range(num_swarm_frames):
                    if num_swarm_frames <= 1:
                        swarm_frame = None
                    current_step = anchor.get_current_step(
                        self.index, swarm_frame, model.directory)
                    restart_checkpoint_filename = anchor\
                        .get_restart_checkpoint_filename(
                            self.index, swarm_frame, model.directory)
                    if (not os.path.exists(restart_checkpoint_filename)) \
                            or force_overwrite: # or umbrella_restart_mode:
                            # TODO: extract from sampling method whether restarts will be done
                        restart = False
                        current_step = 0
                    else:
                        restart = True
                    if current_step > max_total_sim_len:
                        # this simulation has run long enough
                        continue
                    steps_to_go_to_min = min_total_sim_len - current_step
                    steps_to_go_to_min = min_total_sim_len - current_step
                    if steps_to_go_to_min > run_base.STEP_TOLERANCE:
                        logging.info(
                            "Systemwide has not run the minimum number of steps",
                            current_step, "of", min_total_sim_len, 
                            "in swarm index", swarm_frame)
                        total_simulation_length = min_total_sim_len
                        num_transitions = 0
                        anchor_info = [steps_to_go_to_min, num_transitions, 
                                    alpha, restart, total_simulation_length,
                                    swarm_frame]
                        anchor_info_to_run_unsorted.append(anchor_info)

        # sort anchors first by how many steps still to run, then by how many
        # transitions have been completed.    
        anchor_info_to_run = sorted(
            anchor_info_to_run_unsorted, 
            key=lambda item: (min_total_sim_len-item[0], item[1]))
        
        return anchor_info_to_run
        
