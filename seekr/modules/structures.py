@define
class Milestone:
    """
    Within an anchor, a "milestone" is a boundary in CV space,
    that doesn't necessarily need to be used for milestoning theory,
    it's just a convenient name since SEEKR is designed for milestoning.
    Although, this object isn't necessarily a boundary of the anchor -
    the anchor may define a space with boundaries, and other surfaces
    that cross it.
    """
    index: int = field(default=0,
                        validator=[validators.instance_of(int),
                                   validators.ge(0)])
    boundary: bool = field(default=True,
                            validator=validators.instance_of(bool))
    neighbor_anchor_index: int = field(default=0,
                                        validator=[validators.instance_of(int),
                                                   validators.ge(0)])
    alias_index: int = field(default=0,
                            validator=[validators.instance_of(int),
                                       validators.ge(0)])
    variables: dict = field(default=Factory(dict),
                            validator=validators.instance_of(dict))
    # cv_index: I chose not to include this one for SEEKR3
    # TODO: Include the possibility for positions/parameter/topology to be
    #  in a milestone for certain types of milestoning like Elber milestoning?

    def get_cv_index_from_variable(
            self,
            variable_name: str
            ) -> int:
        """
        Return the cv_index for a variable in this milestone.
        """
        return int(variable_name.split("_")[1])
    
    def get_cv_indices(
            self
            ) -> list[int]:
        """
        Return the cv_indices for all variables in this milestone.
        """
        cv_indices: list[int] = []
        for variable_name in self.variables:
            cv_index: int = self.get_cv_index_from_variable(variable_name)
            cv_indices.append(cv_index)
        return cv_indices
    
    def is_point_within(
            self, 
            point: np.ndarray | list,
            tolerance: float = 0.0
            ) -> bool:
        """
        Return whether the point is within the milestone.
        """
        assert len(self.variables) > 0, "No variables within milestone - cannot see "\
            "whether a point is within the milestone."
        me_total_value = 0.0
        neighbor_total_value = 0.0
        for variable_name in self.variables:
            if not variable_name.startswith("me_"):
                continue
            cv_index: int = self.get_cv_index_from_variable(variable_name)
            cv_value = point[cv_index]
            me_i_value = self.variables[f"me_{cv_index}"]
            neighbor_i_value = self.variables[f"neighbor_{cv_index}"]
            me_this_value = (me_i_value - cv_value)**2
            neighbor_this_value = (neighbor_i_value - cv_value)**2
            me_total_value += me_this_value
            neighbor_total_value += neighbor_this_value
                
        distance = me_total_value - neighbor_total_value
        if (distance-tolerance) > 0.0: 
            return False
        
        return True

