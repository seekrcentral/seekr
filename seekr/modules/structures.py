@define
class Milestone:
    """
    Within an anchor, a "milestone" is a boundary in CV space,
    that doesn't necessarily need to be used for milestoning theory,
    it's just a convenient name since seekr was originally for milestoning.
    Although, this object isn't necessarily a boundary of the anchor -
    the anchor may define a space with boundaries, and other surfaces
    that cross it.
    """
    index: int = field(default=0,
                        validator=[validators.instance_of(int),
                                   validators.ge(0)])
    boundary: bool = field(default=True,
                            validator=validators.instance_of(bool))
    neighbor_anchor_index: int = field(default=0,
                                        validator=[validators.instance_of(int),
                                                   validators.ge(0)])
    alias_index: int = field(default=0,
                            validator=[validators.instance_of(int),
                                       validators.ge(0)])
    variables: dict = field(default=Factory(dict),
                            validator=validators.instance_of(dict))
    def get_cv_index_from_variable(
            self,
            variable_name: str
            ) -> int:
        """
        Return the cv_index for a variable in this milestone.
        """
        return int(variable_name.split("_")[1])
    
    def get_cv_indices(
            self
            ) -> list[int]:
        """
        Return the cv_indices for all variables in this milestone.
        """
        cv_indices: list[int] = []
        for variable_name in self.variables:
            if variable_name.startswith("me_"):
                cv_index: int = self.get_cv_index_from_variable(variable_name)
                cv_indices.append(cv_index)
        return cv_indices
    
    def is_point_within(
            self, 
            point: np.ndarray | list,
            tolerance: float = 0.0
            ) -> bool:
        """
        Return whether the point is within the milestone.
        """
        assert len(self.variables) > 0, "No variables within milestone - cannot see "\
            "whether a point is within the milestone."
        me_total_value = 0.0
        neighbor_total_value = 0.0
        for variable_name in self.variables:
            if not variable_name.startswith("me_"):
                continue
            cv_index: int = self.get_cv_index_from_variable(variable_name)
            cv_value = point[cv_index]
            me_i_value = self.variables[f"me_{cv_index}"]
            neighbor_i_value = self.variables[f"neighbor_{cv_index}"]
            me_this_value = (me_i_value - cv_value)**2
            neighbor_this_value = (neighbor_i_value - cv_value)**2
            me_total_value += me_this_value
            neighbor_total_value += neighbor_this_value
        
        distance = me_total_value - neighbor_total_value
        if (distance-tolerance) > 0.0: 
            return False
        
        return True

@define
class Anchor:
    """
    An anchor is a point in CV space. How this point
    is used within SEEKR depends on the enhanced sampling
    method. For instance, an anchor is used with MMVT to define
    a Voronoi cell, whose boundaries become the milestones.
    """
    index: int = field(default=0,
                        validator=[validators.instance_of(int),
                                   validators.ge(0)])
    name: str = field(default="",
                      validator=validators.instance_of(str))
    directory: str = field(default="",
                            validator=validators.instance_of(str))
    bulk_anchor: bool = field(default=False,
                             validator=validators.instance_of(bool))
    scale_types: list[str] = field(default=Factory(list),
                        validator=validators.deep_iterable(
                            member_validator=validators.instance_of(str),
                            iterable_validator=validators.instance_of(list),
                        ))
    scale_parameters_topology: dict[str, engines_structures.Parameters_topology | None] \
        = field(default=Factory(dict),
            validator=validators.instance_of(dict))
    stage_parameters: list[dict | None] = field(default=Factory(list),)
    end_anchor: bool = field(default=False,
                            validator=validators.instance_of(bool))
    bulk_anchor: bool = field(default=False,
                             validator=validators.instance_of(bool))
    neighbor_anchor_indices: list[int] \
        = field(default=Factory(list),
            validator=validators.deep_iterable(
                member_validator=[validators.instance_of(int),
                                    validators.ge(0)],
                iterable_validator=validators.instance_of(list),
            ))
    milestones: list[Milestone] = field(default=Factory(list),)
    variables: dict[str, typing.Any] = field(default=Factory(dict),
                            validator=validators.instance_of(dict))
    
    def has_files(
            self, 
            model: "Seekr_model",
            root_directory: str
            ) -> bool:
        """
        Returns true if any of the anchor's stage directories contain
        outputs from any of the stages.
        """
        for stage in model.stages:
            if stage.has_files(model, anchor_index=self.index):
                return True
            
        return False
    
    def generate_filetree(
            self, 
            model: "Seekr_model",
            root_directory: str
            ) -> None:
        """
        Generate the filetree for this anchor.
        """
        for scale_type in self.scale_types:
            scale = model.get_scale_by_type(scale_type)
            scale.generate_filetree_anchor(self, root_directory)
        
        return
    
    def is_point_within(
            self, 
            point: np.ndarray | list
            ) -> bool:
        """
        Return whether the point is within the anchor.
        """
        assert len(self.milestones) > 0, "No milestones within anchor - cannot see "\
            "whether a point is within the anchor."
        for milestone in self.milestones:
            if milestone.boundary:
                if not milestone.is_point_within(point):
                    return False
        return True
    
    def get_positions_full_paths(
            self,
            root_directory: str,
            input_stage_index: int,
            swarm_id: int | None = None
            ) -> list[str]:
        """
        Construct the full path to the PDB/TXT for this anchor and stage.
        """
        assert len(self.stage_parameters) > input_stage_index, "Stage index "\
            "provided is out of range."
        # NOTE: assert below prevents mypy error of Nonetype not indexable.
        assert self.stage_parameters[input_stage_index] is not None
        positions_base_noext = self.stage_parameters[input_stage_index]["positions"]
        assert isinstance(positions_base_noext, str), "Positions must be a filename str."
        input_stage_dir = self.stage_parameters[input_stage_index]["directory"]
        if swarm_id is None:
            glob_base = [f"{positions_base_noext}*.pdb",
                          f"{positions_base_noext}*.txt",
                          f"{positions_base_noext}*.state"]
        else:
            glob_base = [f"{positions_base_noext}*.swarm_{swarm_id}.pdb",
                         f"{positions_base_noext}*.swarm_{swarm_id}.txt",
                         f"{positions_base_noext}*.swarm_{swarm_id:06d}.state"]
        glob_path = os.path.join(
            root_directory, self.directory, input_stage_dir)
        positions_full_paths = base.glob_or(glob_base, glob_path)
        return positions_full_paths

    #def get_starting_structure_num_swarms(
    def get_starting_structure_swarm_ids(
            self,
            root_directory: str,
            input_stage_index: int
            ) -> list[int]:
        """
        Return the number of frames within a starting structure
        for this anchor. AKA: swarm size. This is done by
        using a glob of the PDB or TXT files that are the 'positions'
        of a stage.
        """
        # TODO: fix docstring
        # NOTE: this used to be the code to handle multiple frames
        #  in a single PDB file
        pdb_full_paths = self.get_positions_full_paths(
            root_directory, input_stage_index)
        swarm_ids = []
        # Loop through the paths, and use the re module to extract
        #  instances where .swarm_123456. is in the filename
        for pdb_full_path in pdb_full_paths:
            match = re.search(r"swarm_(\d+)", pdb_full_path)
            if match:
                swarm_id = int(match.group(1))
                swarm_ids.append(swarm_id)
        swarm_ids.sort()
        return swarm_ids

    def make_var_string(self) -> str:
        """
        Return a string of the variables in this anchor.
        """
        var_list = []
        for variable_key in self.variables:
            if variable_key.startswith("value_"):
                value = self.variables[variable_key]
                var_list.append("{:.3f}".format(value))
        var_string = "_".join(var_list)
        return var_string
    
    def change_positions_filename(
            self,
            new_filename: str,
            stage_number: int) -> None:
        """
        Change the positions filename for this anchor.
        """
        # NOTE: assert below prevents mypy error of Nonetype not indexable.
        assert self.stage_parameters[stage_number+1] is not None, "Stage "\
            f"parameters not defined for anchor {self.index} "\
            f"and stage {stage_number+1}."
        self.stage_parameters[stage_number+1]["positions"] = new_filename
        return
    
    def get_cv_index_from_variable(
            self,
            variable_name: str
            ) -> int:
        """
        Return the cv_index for a variable in this milestone.
        """
        return int(variable_name.split("_")[1])

    def get_cv_indices(
            self
            ) -> list[int]:
        """
        Return the cv_indices for all variables in this milestone.
        """
        cv_indices: list[int] = []
        for variable_name in self.variables:
            if variable_name.startswith("value_"):
                cv_index: int = self.get_cv_index_from_variable(variable_name)
                cv_indices.append(cv_index)
        return cv_indices
    
    def _make_milestone_collection(self):
        """
        Make the dictionaries that allow for easy access of milestone
        indices, aliases, and neighboring indices.
        """
        id_key_alias_value_dict = {}
        alias_key_id_value_dict = {}
        neighbor_id_key_alias_value_dict = {}
        
        for milestone in self.milestones:
                index = milestone.index
                neighbor_index = milestone.neighbor_anchor_index
                alias_index = milestone.alias_index
                id_key_alias_value_dict[index] = alias_index
                neighbor_id_key_alias_value_dict[neighbor_index] = alias_index
                alias_key_id_value_dict[alias_index] = index
        
        return id_key_alias_value_dict, alias_key_id_value_dict, \
            neighbor_id_key_alias_value_dict

    def alias_from_neighbor_id(
            self, 
            neighbor_id: int
            ):
        """
        Take the index of the neighbor anchor's index and provide the
        milestone's alias index.
        """
        _, _, neighbor_id_key_alias_value_dict = self._make_milestone_collection()
        if neighbor_id in neighbor_id_key_alias_value_dict:
            return neighbor_id_key_alias_value_dict[neighbor_id]
        else:
            return None
        
    def id_from_alias(self, alias_id):
        """
        Accept the alias index of a milestone and return the model-wide
        index of the milestone.
        """
        _, alias_key_id_value_dict, _ = self._make_milestone_collection()
        if alias_id in alias_key_id_value_dict:
            return alias_key_id_value_dict[alias_id]
        else:
            return None
        
    def get_stage_output_directory(
            self,
            stage_index: int
            ) -> str:
        """
        Get the output directory for this anchor for a given stage index.
        """
        stage_output_directory \
            = self.stage_parameters[stage_index]["directory"]
        return stage_output_directory

@define
class Seekr_model:
    warning: str = DONT_MODIFY_WARNING
    directory: str = field(default=".",
                            validator=validators.instance_of(str))
    model_version: str = field(default="1.0",
                                 validator=validators.instance_of(str))
    plugins: list[str] = field(default=Factory(list),)
    synopsis_filename: str = field(default="SYNOPSIS",
                                   validator=validators.instance_of(str))
    log_directory: str = field(default="logs",)
    images_and_plots_directory: str = field(default="images_and_plots",
                                            validator=validators\
                                                .instance_of(str))
    temperature: float = field(default=298.15,
                               validator=[validators.instance_of(float),
                                          validators.gt(0)])
    is_toy_system: bool = field(default=False,
                                validator=validators.instance_of(bool))
    scales: list[scales_structures.Scale] = field(default=Factory(list),)
    engines: list[Engine] = field(default=Factory(list),)
    stages: list[scales_structures.Stage] = field(default=Factory(list),)
    collective_variables: list[cv_base.Base_CV] \
        = field(default=Factory(list),)
    num_anchors: int = field(default=0,
                             validator=[validators.instance_of(int),
                                        validators.ge(0)])
    num_milestones: int = field(default=0,
                                validator=[validators.instance_of(int),
                                           validators.ge(0)])
    anchors: list[Anchor] = field(default=Factory(list),)
    
    def using_scale(self, scale_type: str) -> bool:
        """
        Return whether this model is using a given scale type.
        """
        for scale in self.scales:
            if scale.type == scale_type:
                return True
        return False
    
    def using_toy(self) -> bool:
        """
        Return whether this model is of a toy system.
        """
        if self.is_toy_system:
            return True
        else:
            return False

    def get_scale_by_type(
            self, 
            scale_type: str
            ) -> scales_structures.Scale | None:
        """
        Get a scale by its type.
        """
        for scale in self.scales:
            if scale.type == scale_type:
                return scale
        return None

    def get_engine_by_scale_type(
            self, 
            scale_type: str
            ) -> Engine:
        """
        Get an engine by its scale type.
        """
        scale = self.get_scale_by_type(scale_type)
        for engine in self.engines:
            if engine.scale_type == scale.type:
                return engine
        raise ValueError(f"Engine for scale type {scale_type} not found.")
    
    def get_toy_settings(
            self
            ) -> engines_structures.Toy_settings | None:
        """
        Return the toy settings if they exist.
        """
        assert self.using_toy(), "This model is not a toy system."
        for scale in self.scales:
            engine = self.get_engine_by_scale_type(scale.type)
            if engine.can_handle_toy():
                return engine.toy_settings
        raise ValueError("Toy settings not found.")

    def get_timestep_by_type(
            self,
            scale_type: str
            ) -> float:
        """
        Return the timescale used in this model for a given scale type.
        """
        engine = self.get_engine_by_scale_type(scale_type)
        timestep: float = engine.get_timestep()
        return timestep

    def get_bulk_indices(self) -> list[int] | None:
        """
        Get the anchor indices of the bulk states and return as a list of integers
        """
        bulk_indices = []
        for alpha, anchor in enumerate(self.anchors):
            if anchor.bulk_anchor:
                bulk_indices.append(alpha)
        return bulk_indices

    def get_log_directory(
            self, 
            directory: str | None = None
            ) -> str:
        """
        Return the log directory for this model.
        """
        if directory is None:
            return os.path.join(self.directory, self.log_directory)
        else:
            return os.path.join(directory, self.log_directory)
        
    def get_synopsis_filename(
            self, 
            directory: str | None = None
            ) -> str:
        """
        Return the synopsis filename for this model.
        """
        log_directory: str = self.get_log_directory(directory)
        return os.path.join(log_directory, self.synopsis_filename)
    
    def get_random_seed(self) -> int:
        """
        Return the random seed for the MD or BD engines, whichever is higher.
        """
        seeds = [0]
        for scale in self.scales:
            engine = self.get_engine_by_scale_type(scale.type)
            if engine is not None:
                seeds.append(engine.get_random_seed())

        return max(seeds)
        
    def set_random_seeds(
            self, 
            random_seed: int
            ) -> None:
        """
        Set the random seed for the MD and BD engines. Stages?
        """
        for scale in self.scales:
            engine = self.get_engine_by_scale_type(scale.type)
            if engine is not None:
                engine.set_random_seed(random_seed)
        return

    def get_cv_by_name(
            self,
            cv_name: str
            ) -> cv_base.Base_CV:
        """
        Return the collective variable object by name.
        """
        for cv in self.collective_variables:
            if cv.name == cv_name:
                return cv
        raise ValueError(f"CV with name {cv_name} not found.")
    
    def save(
            self, 
            filename: str
            ) -> None:
        """
        Write the model object to a file.
        """
        converter: cattrs.Converter = cattrs.Converter()
        converter.register_unstructure_hook(restraints_structures.Base_restraint,
                                            unstruct_restraint)
        converter.register_unstructure_hook(reporters_structures.Base_reporter,
                                            unstruct_reporter)
        converter.register_unstructure_hook(compl_crit_struct.Base_completion_criteria,
                                            unstruct_completion_criteria)
        converter.register_unstructure_hook(cv_base.Base_CV,
                                            unstruct_collective_variable)
        scales_structures.register_unstructure_hooks(converter)
        seekr_model_dict: dict = converter.unstructure(self)
        seekr_model_dict_noindent: dict = base.wrap_noindent_integers(seekr_model_dict)
        json_dump: str = json.dumps(seekr_model_dict_noindent, indent=4, 
                                    cls=base.NoIndentListEncoder)
        with open(filename, "w") as file:
            file.write(json_dump)
        return
    
    def save_next_model(
            self, 
            model_glob: str, 
            model_base: str, 
            save_old_model: bool=True
            ) -> None:
        """
        Generate a new model file - the next in a series. The old model file(s) 
        will be renamed (optionally) with a numerical index.
        
        Parameters
        ----------
        model : Model()
            The Seekr Model object.
        model_glob : str
            The glob string that will be used to find all old model files.
            Only the base name of the file should be used, not the full path.
        model_base : str
            The base name of the model file. This will be used to rename the
            old model files.
        save_old_model : bool, Default True
            Whether to save the old model file with a new name. This can be
            convenient to set to False if the model should be serialized
            yet we don't care about saving some intermediate model values.
        """
        md_engine = self.get_engine_by_scale_type("molecular_dynamics")
        if md_engine is not None:
            if md_engine.platform_settings is not None:
                cuda_device_index: str = md_engine.get_device_index()
                md_engine.platform_settings.device_index = "0"
            
        model_path: str = os.path.join(self.directory, "model.json")
        if os.path.exists(model_path) and save_old_model:
            # This is expected, because this old model was loaded
            full_model_glob: str = os.path.join(self.directory, model_glob)
            num_globs: int = len(glob.glob(full_model_glob))
            new_pre_model_filename: str = model_base.format(num_globs)
            new_pre_model_path: str = os.path.join(self.directory, 
                                                   new_pre_model_filename)
            logging.info("Renaming model.json to {}".format(new_pre_model_filename))
            copyfile(model_path, new_pre_model_path)
            
        logging.info("Saving new model.json")
        old_rootdir: str = self.directory
        self.directory = "."
        self.save(model_path)
        self.directory = old_rootdir
        if md_engine is not None:
            if md_engine.platform_settings is not None:
                md_engine.set_device_index(cuda_device_index)
        return
    
def load_model(
        filename: str
        ) -> Seekr_model:
    """
    Load a model object from a file.
    """
    with open(filename, "r") as file:
        json_string: str = json.load(file)

    for plugin_name in json_string['plugins']:
        restraints_module_str = base.get_plugin_str(
            plugin_name, submodule_name="restraints")
        if restraints_module_str is not None:
            restraints_module_struct = importlib.import_module(
                restraints_module_str+".structures")
            restraints.update(restraints_module_struct.restraints)
        
        reporters_module_str = base.get_plugin_str(
            plugin_name, submodule_name="reporters")
        if reporters_module_str is not None:
            reporters_module_struct = importlib.import_module(
                reporters_module_str+".structures")
            reporters.update(reporters_module_struct.reporters)

        compl_crit_module_str = base.get_plugin_str(
            plugin_name, submodule_name="completion_criteria")
        if compl_crit_module_str is not None:
            compl_crit_module_struct = importlib.import_module(
                compl_crit_module_str+".structures")
            completion_criteria.update(compl_crit_module_struct.completion_criteria)
        
        cv_module_str = base.get_plugin_str(
            plugin_name, submodule_name="collective_variables")
        if cv_module_str is not None:
            cv_module_struct = importlib.import_module(cv_module_str+".structures")
            cvs.update(cv_module_struct.cvs)
        
        sampl_meth_module_str = base.get_plugin_str(
            plugin_name, submodule_name="sampling_methods")
        if sampl_meth_module_str is not None:
            sampl_meth_module_struct = importlib.import_module(
                sampl_meth_module_str+".structures")
            scales_structures.update_sampling_methods(
                sampl_meth_module_struct.sampling_methods)
            
        
    # Use a cattrs Converter to define how to structure the dictionary input
    converter: cattrs.Converter = cattrs.Converter()
    # Register a structure hook for the Positions_type
    converter.register_structure_hook(base.Positions_type, 
                                      structure_positions_type_union)
    converter.register_structure_hook(base.Float_or_list_type, 
                                      structure_float_or_list_type_union)
    converter.register_structure_hook(base.Int_or_list_type, 
                                      structure_int_or_list_type_union)
    converter.register_structure_hook(restraints_structures.Base_restraint,
                                        struct_restraint)
    converter.register_structure_hook(reporters_structures.Base_reporter,
                                        struct_reporter)
    converter.register_structure_hook(compl_crit_struct.Base_completion_criteria,
                                        struct_completion_criteria)
    converter.register_structure_hook(cv_base.Base_CV,
                                        struct_collective_variable)
    
    scales_structures.register_structure_hooks(converter)
    model: Seekr_model = converter.structure(json_string, Seekr_model)
    if model.directory == ".":
        model_dir = os.path.dirname(filename)
