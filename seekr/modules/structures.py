    def save_next_model(
            self, 
            model_glob: str, 
            model_base: str, 
            save_old_model: bool=True
            ) -> None:
        """
        Generate a new model file - the next in a series. The old model file(s) 
        will be renamed (optionally) with a numerical index.
        
        Parameters
        ----------
        model : Model()
            The Seekr Model object.
        model_glob : str
            The glob string that will be used to find all old model files.
            Only the base name of the file should be used, not the full path.
        model_base : str
            The base name of the model file. This will be used to rename the
            old model files.
        save_old_model : bool, Default True
            Whether to save the old model file with a new name. This can be
            convenient to set to False if the model should be serialized
            yet we don't care about saving some intermediate model values.
        """
        md_engine = self.get_engine_by_scale_type("molecular_dynamics")
        if md_engine is not None:
            if md_engine.platform_settings is not None:
                cuda_device_index: str = md_engine.get_device_index()
                md_engine.platform_settings.device_index = "0"
            
        model_path: str = os.path.join(self.directory, "model.json")
        if os.path.exists(model_path) and save_old_model:
            # This is expected, because this old model was loaded
            full_model_glob: str = os.path.join(self.directory, model_glob)
            num_globs: int = len(glob.glob(full_model_glob))
            new_pre_model_filename: str = model_base.format(num_globs)
            new_pre_model_path: str = os.path.join(self.directory, 
                                                   new_pre_model_filename)
            logger.info("Renaming model.json to {}".format(new_pre_model_filename))
            copyfile(model_path, new_pre_model_path)

        logger.info("Saving new model.json")
        old_rootdir: str = self.directory
        self.directory = "."
        self.save(model_path)
        self.directory = old_rootdir
        if md_engine is not None:
            if md_engine.platform_settings is not None:
                md_engine.set_device_index(cuda_device_index)
        return
    
    def load_cvs(
            self, 
            set_name: str
            ) -> None:
        """
        Load any collective variables that need to be loaded during prepare.
        """
        cv_directory = os.path.join(self.directory, "collective_variable_sets")
        this_cv_set_directory = os.path.join(
            cv_directory, set_name)
        this_cv_set_glob = os.path.join(this_cv_set_directory, "*.json")
        cv_files = glob.glob(this_cv_set_glob)
        self.collective_variables = []
        for cv_file in cv_files:
            self.collective_variables.append(
                cv_structures.load_cv_from_file(cv_file))
        # Sort CVs by .index attribute
        self.collective_variables.sort(key=lambda cv: cv.index)
        # Duplicate indices usually mean orphaned CV JSON files from a prior
        # prepare were left on disk. clear_cv_set() before rewriting the set.
        seen_indices: dict[int, str] = {}
        for cv in self.collective_variables:
            if cv.index in seen_indices:
                raise ValueError(
                    f"Duplicate CV index {cv.index} for "
                    f"'{seen_indices[cv.index]}' and '{cv.name}' in "
                    f"{this_cv_set_directory}. Stale collective-variable files "
                    f"may remain from a previous prepare; re-run prepare "
                    f"(which clears the CV set) or remove orphaned *.json "
                    f"files under that directory.")
            seen_indices[cv.index] = cv.name
        return
    
    def load_selections(
            self, 
            set_name: str
            ) -> None:
        """
        Load any selections that need to be loaded during prepare.
        """
        selections_directory = os.path.join(self.directory, "selection_sets")
        this_selections_set_directory = os.path.join(
            selections_directory, set_name)
        for engine in self.engines:
            engine.load_selections(
                this_selections_set_directory)
        return
    
    def load_anchor_set(
            self, 
            set_name: str
            ) -> None:
        """
        Load any anchor sets that need to be loaded during prepare.
        """
        milestone_indices = set()
        anchor_sets_directory = os.path.join(self.directory, "anchor_sets")
        this_anchor_set_directory = os.path.join(
            anchor_sets_directory, set_name)
        this_anchor_set_glob = os.path.join(this_anchor_set_directory, "anchor_*.json")
        anchor_files = glob.glob(this_anchor_set_glob)
        self.anchors = []
        for anchor_file in anchor_files:
            anchor = load_anchor_from_file(anchor_file)
            for milestone in anchor.milestones:
                milestone_indices.add(milestone.index)
            self.anchors.append(anchor)
            
        # Sort anchors by .index attribute
        self.anchors.sort(key=lambda anchor: anchor.index)
        self.num_anchors = len(self.anchors)
        self.num_milestones = len(milestone_indices)
        return

