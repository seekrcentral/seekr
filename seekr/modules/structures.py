    def using_bd(self) -> bool:
        """
        Return whether this model is using BD
        """
        if self.bd_engine is None:
            return False
        else:
            return True
    
    def using_md(self) -> bool:
        """
        Return whether this model is using MD
        """
        if self.md_engine is None:
            return False
        else:
            return True

