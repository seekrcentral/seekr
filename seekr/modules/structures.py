    variables: dict = field(default=Factory(dict),
                            validator=validators.instance_of(dict))
    
    def has_files(
            self, 
            root_directory: str
            ) -> bool:
        """
        Returns true if any of the anchor's stage directories contain
        outputs from any of the stages.
        """
        for stage_directory in self.stage_directories:
            stage_directory = os.path.join(
                root_directory, self.directory, stage_directory)
            if os.path.exists(stage_directory):
                # TODO: is this too general? Should the glob specify a more
                # specific pattern? Perhaps from the stage object itself?
                glob_str = "*"
                output_files_glob = os.path.join(stage_directory, glob_str)
                if len(glob.glob(output_files_glob)) > 0:
                    return True
                else:
                    continue
            else:
                continue
        return False
    
    def generate_filetree(
            self, 
            root_directory: str
            ) -> None:
        """
        Generate the filetree for this anchor.
        """
        if self.md:
            anchor_dict: dict[str, dict] = {self.directory: {}}
            #md_parameters_topology = self.stage_parameters[0]["md_parameters_topology"]
            #md_parameters_topology = self.md_parameters_topology
            #positions = self.stage_parameters[0]["positions"]
            #if (md_parameters_topology is not None) \
            #        or (positions is not None and positions != ""):
            #    anchor_dict[self.directory][base.INITIAL_DIRECTORY] = {}
            for stage_parameter in self.stage_parameters:
                stage_directory = stage_parameter["directory"]
                anchor_dict[self.directory][stage_directory] = {}

            base.make_tree(root_directory, anchor_dict)

        elif self.bd:
            # If anchor.bd is True, while anchor.md is False, then this
            # must be the b-surface directory
            b_surface_dict: dict[str, dict] = {self.directory: {}}
            base.make_tree(root_directory, b_surface_dict)

        return
    
    def is_point_within(
            self, 
            point: np.ndarray | list
            ) -> bool:
        """
        Return whether the point is within the anchor.
        """
        assert len(self.milestones) > 0, "No milestones within anchor - cannot see "\
            "whether a point is within the anchor."
        for milestone in self.milestones:
            if milestone.boundary:
                if not milestone.is_point_within(point):
                    return False
            
        return True
    
    def get_positions_pdb_full_path(
            self,
            model: "Seekr_model",
            input_stage_index: int
            ) -> str:
        """
        Construct the full path to the PDB for this anchor and stage.
        """
        assert len(self.stage_parameters) > input_stage_index, "Stage index "\
            "provided is out of range."
        assert self.stage_parameters[input_stage_index] is not None
        positions = self.stage_parameters[input_stage_index]["positions"]
        assert isinstance(positions, str), "Positions must be a filename str."
        input_stage_dir = self.stage_parameters[input_stage_index]["directory"]
        positions_full_path: str = os.path.join(
            model.directory, self.directory, input_stage_dir, positions)
        return positions_full_path

    def get_starting_structure_num_frames(
            self,
            model: "Seekr_model",
            input_stage_index: int
            ) -> int:
        """
        Return the number of frames within a starting structure
        for this anchor. AKA: swarm size.
        """
        if isinstance(self.positions, str):
            # Load the PDB file and count the number of frames
            pdb_full_path = self.get_positions_pdb_full_path(model, input_stage_index)
            num_frames = model.md_engine.get_pdb_num_frames(pdb_full_path)
            return num_frames
        elif isinstance(self.positions, list):
            return len(self.positions)
        else:
            return 0
        
    def cleanse_outputs(
            self,
            model: "Seekr_model"
            ) -> None:
        """
        Delete all simulation outputs from an existing anchor.
        """
        for i, stage in enumerate(model.stages):
            full_directory = os.path.join(model.directory, self.directory, 
                                          stage.get_directory_name())
            if os.path.exists(full_directory):
                file_globs = stage.sampling_method.get_output_globs()
                for file_glob in file_globs:
                    full_glob = os.path.join(full_directory, file_glob)
                    for file in glob.glob(full_glob):
                        os.remove(file)

        return
    
    def get_current_step(
            self, 
            stage_index: int, 
            swarm_index: int | None,
            root_directory: str):
        """
        Return the current step for a given stage index.
        """
        assert len(self.stage_parameters) > stage_index, "Stage index "\
            "provided is out of range."
        assert self.stage_parameters[stage_index] is not None
        if self.md:
            stage_directory = self.stage_parameters[stage_index]["directory"]
            full_directory = os.path.join(root_directory, self.directory, stage_directory)
            checkpoint_info_basename = run_base.get_checkpoint_information_filename(swarm_index)
            checkpoint_information_filename = os.path.join(
                full_directory, checkpoint_info_basename)
            if os.path.exists(checkpoint_information_filename):
                checkpoint_information = run_base.load_checkpoint_information(
                    checkpoint_information_filename)
                current_step = checkpoint_information.current_step
            else: 
                current_step = 0
            return current_step
        else:
            raise NotImplementedError("BD current step not yet implemented.")
    
    def get_restart_checkpoint_filename(
            self, 
            stage_index: int, 
            swarm_index: int | None,
            root_directory: str):
        """
        Return the restart checkpoint filename for a given stage index.
        """
        assert len(self.stage_parameters) > stage_index, "Stage index "\
            "provided is out of range."
        assert self.stage_parameters[stage_index] is not None
        if self.md:
            stage_directory = self.stage_parameters[stage_index]["directory"]
            full_directory = os.path.join(root_directory, self.directory, stage_directory)
            restart_checkpoint_basename = run_base.get_restart_checkpoint_filename(swarm_index)
            restart_checkpoint_filename = os.path.join(
                full_directory, restart_checkpoint_basename)
            return restart_checkpoint_filename
        else:
            raise NotImplementedError("No BD restart checkpoint.")
    
